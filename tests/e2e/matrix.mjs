// tests/e2e/matrix.mjs — матрица прогонов: ширина × объём данных × тема.
//
// Требование: REQ-UI-GEOMETRY (docs/SPEC.md §7). Методичка: gld/ui-contract.txt §1.4.
// Используют: tests/e2e/geo-*.spec.mjs.
//
// ЗАЧЕМ МАТРИЦА
//
// Методичка называет причину прямо: «тестовый контур ≠ ваш контур». Тесты гоняются на
// одном размере окна и десяти записях, а человек работает на своём экране с двумя
// сотнями. Всё, что ломается от объёма или ширины, оказывается вне покрытия.
//
// У этого проекта уже есть свидетельство: вложенный `.field` давал скролл ровно на
// 800×600 и не давал на 1280. Один размер окна — один пропущенный дефект.
//
// ТРИ ОСИ
//
//   ширина  — 800 / 1280 / 1920. Первая обязательна: окно выбора всплывающее,
//             и на ноутбуке оно именно такое.
//   объём   — 0 / 20 / 200 промптов. Ноль — законное состояние (первый запуск),
//             двести — то, к чему библиотека придёт за год.
//   тема    — светлая / тёмная. Обе объявлены в контракте, значит обе проверяются.
//
// 3 × 3 × 2 = 18 ячеек. Полный перебор нужен не всем инвариантам: базовый набор —
// да, специфичные проверки — там, где элемент существует.

/** Ширины окна. Высота 800: ниже начинается вертикальная прокрутка, и это законно. */
export const WIDTHS = [
  { w: 800, h: 600, name: '800×600' },
  { w: 1280, h: 800, name: '1280×800' },
  { w: 1920, h: 1080, name: '1920×1080' },
];

/** Объёмы библиотеки. Имена короткие: они попадают в название теста. */
export const VOLUMES = [
  { count: 0, name: 'пусто' },
  { count: 20, name: '20 промптов' },
  { count: 200, name: '200 промптов' },
];

export const THEMES = ['light', 'dark'];

/**
 * Промпты для заданного объёма.
 *
 * Данные НЕ однородные, и это важно. Однородный список «Промпт 1…N» не ломает
 * вёрстку никогда, а живая библиотека ломает: длинные заголовки, длинные слова без
 * пробелов, кириллица, разные группы, разная частота использования. Каждый пятый
 * получает заголовок на всю строку, каждый седьмой — путь без пробелов в теле.
 */
export const promptsFor = (count) => {
  const groups = ['code', 'research', 'core', 'parsing', 'chatbox'];
  const out = [];

  for (let i = 0; i < count; i += 1) {
    const long = i % 5 === 0;
    const unbroken = i % 7 === 0;

    out.push({
      id: `p-${String(i).padStart(3, '0')}`,
      group: groups[i % groups.length],
      title: long
        ? `Очень длинное название промпта номер ${i}, которое обязано поместиться в строку без обрезания текста`
        : `Промпт ${i}`,
      body: unbroken
        ? `C:\\Users\\Example\\Desktop\\codeproj\\main-md\\prompt-system\\prompts\\code\\файл-${i}.md`
        : `Тело промпта ${i}. Несколько слов, чтобы превью было непустым.`,
      used: i % 13,
      pin: i < 3 ? i + 1 : null,
    });
  }

  return out;
};

/**
 * Записи журнала буфера для заданного объёма.
 * Одна из пяти — длинная без пробелов: журнал растягивался именно на таких.
 */
export const clipsFor = (count) => Array.from({ length: count }, (_, i) => ({
  text: i % 5 === 0
    ? `ключ=${'x'.repeat(300)}`
    : `Запись журнала номер ${i}. Обычный текст в несколько слов.`,
}));

/** Все 18 ячеек: для тестов, которые гоняют полный перебор. */
export const cells = () => {
  const out = [];
  for (const size of WIDTHS) {
    for (const vol of VOLUMES) {
      for (const theme of THEMES) {
        out.push({ size, vol, theme, name: `${size.name} · ${vol.name} · ${theme}` });
      }
    }
  }
  return out;
};

/**
 * Подготовка ячейки: размер окна, данные, тема.
 *
 * Тема ставится через настройки, а не подменой атрибута: так проверяется тот путь,
 * которым темой пользуется человек. Подмена `data-theme` руками показала бы, что
 * стили есть, но не показала бы, что переключатель работает.
 */
export const setupCell = async (page, deck, cell, { withClips = false } = {}) => {
  await deck.reset();
  await page.setViewportSize({ width: cell.size.w, height: cell.size.h });

  if (cell.vol.count > 0) deck.seed(promptsFor(cell.vol.count));
  if (withClips && cell.vol.count > 0) {
    for (const clip of clipsFor(Math.min(cell.vol.count, 30))) {
      // eslint-disable-next-line no-await-in-loop
      await deck.api('/api/clips', { method: 'POST', body: clip });
    }
  }

  await deck.settings({ ui: { theme: cell.theme } });
};
