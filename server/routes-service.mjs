// server/routes-service.mjs — управление сервисом из окна управления.
//
// Требование: REQ-API-SERVICE (docs/SPEC.md §6). Сценарий S-08.
// Тест: tests/e2e/service.spec.mjs.
//
// Отдельный файл по той же причине, что и routes-clips.mjs: server/routes.mjs
// упёрся в лимит 300 строк, а лимит не обходится (docs/RULES.md §3).
//
// Почему здесь нет действия «запустить». Это окно отдал сам сервис: страница
// доходит до браузера через тот же процесс, который её обслуживает. Пока окно
// видно — сервис работает, и запускать нечего. Когда сервис остановлен, страница
// не открывается вовсе, и просить её о запуске некого. Запуск возможен только
// снаружи: из трея или ярлыком. Поэтому «Запустить» всегда недоступна, и причина
// написана рядом — это честнее кнопки, которая молча ничего не делает.
//
// Остановка и перезапуск идут в два шага, как обмен закреплений: сначала сервер
// называет последствие, потом человек подтверждает (docs/RULES.md §6). Причина
// конкретная: остановка снимает горячие клавиши и слежку за буфером, то есть
// выключает всё, ради чего программа запущена. Узнать об этом после факта —
// значит потом искать, «почему больше не работает Ctrl+Alt+Q».

import { sendJson, sendError, readJsonBody } from './http.mjs';

export const SERVICE_ROUTES = [
  ['GET', '/api/service'],
  ['POST', '/api/service'],
];

/** Последствие каждого действия словами, которые увидит человек. */
export const SERVICE_PLAN = {
  stop: {
    word: 'Остановить сервис?',
    // Про значок сказано прямо, и это не мелочь: мост остаётся жив, поэтому
    // горячая клавиша откроет страницу, которая не отвечает. Так же ведёт себя
    // остановка из трея (bridge/tray.mjs) — чтобы закрыть всё, там есть «Выход».
    effect: 'Слежка за буфером остановится, окно выбора не откроется. '
      + 'Промпты и журнал останутся на диске. Значок в трее останется: '
      + 'запустить обратно — из его меню, закрыть совсем — «Выход» в нём же.',
  },
  restart: {
    word: 'Перезапустить сервис?',
    effect: 'Окно закроется на несколько секунд. Мост перечитает горячие клавиши '
      + 'из настроек — именно это применяет только что изменённые сочетания.',
  },
};

/** Почему «Запустить» недоступна. Текст уходит в интерфейс, а не живёт в нём. */
export const START_WHY = 'сервис уже работает — это окно отдал он. '
  + 'Запуск возможен значком в трее или ярлыком';

export const SERVICE_HANDLERS = {
  /** Что окно управления вправе предложить. Список приходит с сервера, не из разметки. */
  'GET /api/service': ({ res, control }) => {
    const can = typeof control?.shutdown === 'function';
    sendJson(res, 200, {
      actions: {
        start: { allowed: false, why: START_WHY },
        stop: { allowed: can, why: can ? null : 'процесс не умеет останавливать себя' },
        restart: { allowed: can, why: can ? null : 'процесс не умеет перезапускать себя' },
      },
      plans: SERVICE_PLAN,
    });
  },

  'POST /api/service': async ({ req, res, control }) => {
    const body = await readJsonBody(req);
    if (!body.ok) return sendError(res, 400, 'bad_json', body.message);

    const action = String(body.data.action ?? '');

    if (action === 'start') {
      return sendError(res, 409, 'already_running', START_WHY,
        { field: 'action', expected: 'stop | restart' });
    }

    const plan = SERVICE_PLAN[action];
    if (!plan) {
      return sendError(res, 400, 'bad_action', `неизвестное действие «${action}»`,
        { field: 'action', expected: Object.keys(SERVICE_PLAN).join(' | ') });
    }

    // Первый запрос только объясняет. Выполнять на нём значило бы останавливать
    // сервис по одному нажатию без предупреждения.
    if (body.data.confirm !== true) {
      return sendJson(res, 200, { plan: { action, ...plan } });
    }

    if (typeof control?.shutdown !== 'function') {
      return sendError(res, 501, 'no_control',
        'этот процесс не умеет останавливать себя: сервер поднят как встроенный');
    }

    // Ответ уходит ДО остановки. Иначе соединение оборвалось бы на середине, и
    // интерфейс сказал бы «нет связи с сервисом» — правду, но не о том, что
    // произошло: человек не отличил бы выполненную команду от сбоя.
    sendJson(res, 200, { done: action, plan: { action, ...plan } });
    control.shutdown({ restart: action === 'restart' });
    return true;
  },
};
